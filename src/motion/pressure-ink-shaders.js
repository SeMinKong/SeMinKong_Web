export const PRESSURE_SHADER = shader(
  '#version 300 es',
  'precision highp float;',
  '',
  'in vec2 vUv;',
  'out vec4 outColor;',
  '',
  'uniform sampler2D uPressure;',
  'uniform sampler2D uDivergence;',
  'uniform vec2 uTexel;',
  ...OBSTACLE_GLSL,
  '',
  'float readPressure(vec2 uv, float center) {',
  '  return isSolid(uv) ? center : texture(uPressure, clamp(uv, 0.0, 1.0)).x;',
  '}',
  '',
  'void main() {',
  '  if (isSolid(vUv)) {',
  '    outColor = vec4(0.0);',
  '    return;',
  '  }',
  '',
  '  float center = texture(uPressure, vUv).x;',
  '  float left = readPressure(vUv - vec2(uTexel.x, 0.0), center);',
  '  float right = readPressure(vUv + vec2(uTexel.x, 0.0), center);',
  '  float bottom = readPressure(vUv - vec2(0.0, uTexel.y), center);',
  '  float top = readPressure(vUv + vec2(0.0, uTexel.y), center);',
  '  float divergence = texture(uDivergence, vUv).x;',
  '  float pressure = (left + right + bottom + top - divergence) * 0.25;',
  '  outColor = vec4(pressure, 0.0, 0.0, 1.0);',
  '}'
);

export const GRADIENT_SHADER = shader(
  '#version 300 es',
  'precision highp float;',
  '',
  'in vec2 vUv;',
  'out vec4 outColor;',
  '',
  'uniform sampler2D uPressure;',
  'uniform sampler2D uVelocity;',
  'uniform vec2 uTexel;',
  ...OBSTACLE_GLSL,
  '',
  'float readPressure(vec2 uv, float center) {',
  '  return isSolid(uv) ? center : texture(uPressure, clamp(uv, 0.0, 1.0)).x;',
  '}',
  '',
  'void main() {',
  '  if (isSolid(vUv)) {',
  '    outColor = vec4(0.0);',
  '    return;',
  '  }',
  '',
  '  float center = texture(uPressure, vUv).x;',
  '  vec2 leftUv = vUv - vec2(uTexel.x, 0.0);',
  '  vec2 rightUv = vUv + vec2(uTexel.x, 0.0);',
  '  vec2 bottomUv = vUv - vec2(0.0, uTexel.y);',
  '  vec2 topUv = vUv + vec2(0.0, uTexel.y);',
  '  float left = readPressure(leftUv, center);',
  '  float right = readPressure(rightUv, center);',
  '  float bottom = readPressure(bottomUv, center);',
  '  float top = readPressure(topUv, center);',
  '  vec2 velocity = texture(uVelocity, vUv).xy - (0.5 * vec2(right - left, top - bottom));',
  '  if (isSolid(leftUv) || isSolid(rightUv)) velocity.x = 0.0;',
  '  if (isSolid(bottomUv) || isSolid(topUv)) velocity.y = 0.0;',
  '  if ((vUv.x < uTexel.x * 2.0 && velocity.x < 0.0) || (vUv.x > 1.0 - uTexel.x * 2.0 && velocity.x > 0.0)) velocity.x = 0.0;',
  '  if ((vUv.y < uTexel.y * 2.0 && velocity.y < 0.0) || (vUv.y > 1.0 - uTexel.y * 2.0 && velocity.y > 0.0)) velocity.y = 0.0;',
  '  outColor = vec4(velocity, 0.0, 1.0);',
  '}'
);

export const DISPLAY_SHADER = shader(
  '#version 300 es',
  'precision highp float;',
  '',
  'in vec2 vUv;',
  'out vec4 outColor;',
  '',
  'uniform sampler2D uDye;',
  'uniform vec2 uDyeSize;',
  'uniform vec2 uResolution;',
  'uniform float uTime;',
  'uniform vec3 uPaper;',
  'uniform vec3 uRaisedPaper;',
  'uniform vec3 uInk;',
  'uniform vec3 uSignal;',
  'uniform float uIntensity;',
  ...OBSTACLE_GLSL,
  ...MANUAL_BILINEAR_GLSL,
  '',
  'float hash(vec2 point) {',
  '  return fract(sin(dot(point, vec2(127.1, 311.7))) * 43758.5453123);',
  '}',
  '',
  'void main() {',
  '  vec2 texel = 1.0 / uDyeSize;',
  '  vec2 center = sampleBilinear(uDye, vUv, uDyeSize).xy;',
  '  vec2 broad = (',
  '    sampleBilinear(uDye, vUv + vec2(texel.x * 2.5, 0.0), uDyeSize).xy +',
  '    sampleBilinear(uDye, vUv - vec2(texel.x * 2.5, 0.0), uDyeSize).xy +',
  '    sampleBilinear(uDye, vUv + vec2(0.0, texel.y * 2.5), uDyeSize).xy +',
  '    sampleBilinear(uDye, vUv - vec2(0.0, texel.y * 2.5), uDyeSize).xy',
  '  ) * 0.25;',
  '',
  '  float graphiteCore = 1.0 - exp(-center.x * 1.48);',
  '  float graphiteWash = 1.0 - exp(-broad.x * 0.86);',
  '  float graphiteEdge = clamp(abs(center.x - broad.x) * 0.65, 0.0, 1.0);',
  '  float signal = 1.0 - exp(-center.y * 1.72);',
  '  float clearMask = smoothstep(-0.006, 0.035, quietDistance(vUv));',
  '',
  '  graphiteCore *= clearMask;',
  '  graphiteWash *= clearMask;',
  '  graphiteEdge *= clearMask;',
  '  signal *= clearMask;',
  '',
  '  float lift = (1.0 - vUv.y) * 0.16 + (1.0 - smoothstep(-0.01, 0.16, quietDistance(vUv))) * 0.12;',
  '  vec3 color = mix(uPaper, uRaisedPaper, lift);',
  '  float graphiteAmount = clamp((graphiteWash * 0.15) + (graphiteCore * 0.23) + (graphiteEdge * 0.1), 0.0, 0.42) * uIntensity;',
  '  color = mix(color, uInk, graphiteAmount);',
  '  color = mix(color, uSignal, clamp(signal * 0.22 * uIntensity, 0.0, 0.22));',
  '',
  '  float grain = (hash(gl_FragCoord.xy + floor(uTime * 2.0)) - 0.5) * 0.005;',
  '  outColor = vec4(color + grain, 1.0);',
  '}'
);
