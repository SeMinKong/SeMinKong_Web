import { MAX_SPLATS } from './pressure-ink-config.js';

const shader = (...lines) => lines.join('\n');

export const PRESSURE_VERTEX_SHADER = shader(
  '#version 300 es',
  'precision highp float;',
  '',
  'out vec2 vUv;',
  '',
  'void main() {',
  '  vec2 position = vec2(',
  '    (gl_VertexID == 1) ? 3.0 : -1.0,',
  '    (gl_VertexID == 2) ? 3.0 : -1.0',
  '  );',
  '  vUv = position * 0.5 + 0.5;',
  '  gl_Position = vec4(position, 0.0, 1.0);',
  '}'
);

const OBSTACLE_GLSL = [
  'uniform vec4 uQuiet;',
  'uniform float uAspect;',
  '',
  'float roundedBoxSdf(vec2 point, vec2 halfSize, float radius) {',
  '  vec2 edge = abs(point) - halfSize + radius;',
  '  return min(max(edge.x, edge.y), 0.0) + length(max(edge, 0.0)) - radius;',
  '}',
  '',
  'float quietDistance(vec2 uv) {',
  '  vec2 point = uv - uQuiet.xy;',
  '  point.x *= uAspect;',
  '  vec2 halfSize = vec2(uQuiet.z * uAspect, uQuiet.w);',
  '  return roundedBoxSdf(point, halfSize, 0.045);',
  '}',
  '',
  'bool isSolid(vec2 uv) {',
  '  return quietDistance(uv) < 0.0;',
  '}'
];

const MANUAL_BILINEAR_GLSL = [
  'vec4 sampleBilinear(sampler2D source, vec2 uv, vec2 size) {',
  '  vec2 position = (clamp(uv, 0.0, 1.0) * size) - 0.5;',
  '  vec2 base = floor(position);',
  '  vec2 weight = fract(position);',
  '  vec2 first = (base + 0.5) / size;',
  '  vec2 second = (base + 1.5) / size;',
  '  vec4 bottom = mix(texture(source, vec2(first.x, first.y)), texture(source, vec2(second.x, first.y)), weight.x);',
  '  vec4 top = mix(texture(source, vec2(first.x, second.y)), texture(source, vec2(second.x, second.y)), weight.x);',
  '  return mix(bottom, top, weight.y);',
  '}'
];

export const VELOCITY_SPLAT_SHADER = shader(
  '#version 300 es',
  'precision highp float;',
  '',
  'in vec2 vUv;',
  'out vec4 outColor;',
  '',
  'uniform sampler2D uSource;',
  'uniform vec4 uSplatData[' + MAX_SPLATS + '];',
  'uniform vec2 uSplatForce[' + MAX_SPLATS + '];',
  'uniform int uSplatCount;',
  ...OBSTACLE_GLSL,
  '',
  'void main() {',
  '  if (isSolid(vUv)) {',
  '    outColor = vec4(0.0);',
  '    return;',
  '  }',
  '',
  '  vec2 velocity = texture(uSource, vUv).xy;',
  '  for (int index = 0; index < ' + MAX_SPLATS + '; index++) {',
  '    if (index >= uSplatCount) break;',
  '    vec4 splat = uSplatData[index];',
  '    vec2 delta = vUv - splat.xy;',
  '    delta.x *= uAspect;',
  '    float influence = exp(-dot(delta, delta) / max(splat.z * splat.z, 0.00002));',
  '    velocity += uSplatForce[index] * splat.w * influence;',
  '  }',
  '',
  '  float magnitude = length(velocity);',
  '  velocity *= min(1.0, 1.35 / max(magnitude, 0.0001));',
  '  outColor = vec4(velocity, 0.0, 1.0);',
  '}'
);

